"""sphinxcontrib.matlab_apidoc._cli.
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~

Command line of ``sphinx-matlab-apidoc`` (plan.md Section 2.8). Settings
come from flags only; keep them equal to ``conf.py``.
"""

from __future__ import annotations

import argparse
import contextlib
import logging
import os
import sys
import time

from sphinx.errors import ConfigError

from .. import mat_naming
from ..mat_types import (
    DEFAULT_INCLUDE_PATTERNS,
    IndexSettings,
    SourceFilter,
    _normalize_pattern,
    build_index,
    check_pattern_folders,
)
from ._generate import ApidocOptions, generate

#: exit status for usage and settings errors (as argparse)
USAGE_ERROR = 2


def _version():
    try:
        from importlib.metadata import version

        return version("sphinxcontrib-matlabdomain")
    except Exception:
        return "0.0.0"


def get_parser():
    parser = argparse.ArgumentParser(
        prog="sphinx-matlab-apidoc",
        usage="%(prog)s [OPTIONS] -o OUTPUT_DIR ROOT",
        description=(
            "Write reST pages with sphinxcontrib-matlabdomain directives for the "
            "MATLAB files below ROOT: one page per folder, mirroring the folder "
            "tree. Existing files are kept unless -f is given."
        ),
        epilog=(
            "ROOT is the folder matlab_src_code_project_root points to. Keep "
            "--include, --exclude, --matlab-version and --encoding equal to "
            "conf.py."
        ),
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {_version()}")
    parser.add_argument("root", metavar="ROOT", help="the MATLAB project root")
    parser.add_argument(
        "-o", "--output-dir", required=True, help="folder for the generated files"
    )
    parser.add_argument(
        "--include",
        action="append",
        metavar="PATTERN",
        help="files to document, a glob relative to ROOT like "
        "matlab_src_include_patterns (repeatable; default: **/*)",
    )
    parser.add_argument(
        "--exclude",
        action="append",
        default=[],
        metavar="PATTERN",
        help="files to leave out, like matlab_src_exclusion_patterns (repeatable)",
    )
    parser.add_argument(
        "--matlab-version",
        default=mat_naming.DEFAULT_MATLAB_VERSION,
        help="like matlab_version (default: %(default)s)",
    )
    parser.add_argument(
        "--encoding", help="like matlab_src_encoding (default: UTF-8, as MATLAB)"
    )
    parser.add_argument(
        "-f", "--force", action="store_true", help="overwrite existing files"
    )
    parser.add_argument(
        "-n",
        "--dry-run",
        action="store_true",
        help="write and remove nothing; list what would change",
    )
    parser.add_argument(
        "-e", "--separate", action="store_true", help="one page per file"
    )
    parser.add_argument(
        "-d",
        "--maxdepth",
        type=int,
        default=4,
        help="maximum depth of the toctrees (default: %(default)s)",
    )
    parser.add_argument(
        "--tocfile",
        default="index",
        help="name of the root folder's page (default: %(default)s)",
    )
    parser.add_argument(
        "--suffix", default="rst", help="file suffix (default: %(default)s)"
    )
    parser.add_argument(
        "-t",
        "--templatedir",
        help="folder with templates (folder.rst.jinja, object.rst.jinja) that "
        "replace the defaults",
    )
    parser.add_argument(
        "--remove-old",
        action="store_true",
        help="delete files with the suffix below OUTPUT_DIR (not in folders "
        "starting with '.' or '_') that start with the marker line and were "
        "not generated by this run",
    )
    parser.add_argument(
        "-q",
        "--quiet",
        action="store_true",
        help="no output on stdout, just warnings on stderr",
    )
    return parser


def _name(value, option):
    if not value or any(sep in value for sep in "/\\"):
        raise ConfigError(f"{option} {value!r} must be a file name.")
    return value


def _settings(args):
    """``(IndexSettings, ApidocOptions)`` of the flags, or ConfigError."""
    root = os.path.abspath(args.root)
    if not os.path.isdir(root):
        raise ConfigError(f"ROOT {args.root!r} is not a folder.")
    include = DEFAULT_INCLUDE_PATTERNS if args.include is None else args.include
    include = [_normalize_pattern(p, "--include") for p in include]
    exclude = [_normalize_pattern(p, "--exclude") for p in args.exclude]
    check_pattern_folders(SourceFilter(include, exclude), root, "--include")
    if args.encoding is not None:
        try:
            # not b"".decode(): it skips the check for non-text codecs (rot13)
            "a".encode(args.encoding)
        except (LookupError, TypeError) as err:
            raise ConfigError(
                f"--encoding {args.encoding!r} is not a known text encoding."
            ) from err
    try:
        mat_naming.resolve_namelengthmax(args.matlab_version, None)
    except ValueError as err:
        raise ConfigError(f"--matlab-version: {err}") from err
    if os.path.exists(args.output_dir) and not os.path.isdir(args.output_dir):
        raise ConfigError(f"-o {args.output_dir!r} is not a folder.")
    if args.templatedir is not None and not os.path.isdir(args.templatedir):
        raise ConfigError(f"-t {args.templatedir!r} is not a folder.")
    settings = IndexSettings(
        root=root,
        include=tuple(include),
        exclude=tuple(exclude),
        encoding=args.encoding,
        matlab_version=args.matlab_version,
    )
    options = ApidocOptions(
        output_dir=args.output_dir,
        force=args.force,
        dry_run=args.dry_run,
        separate=args.separate,
        maxdepth=args.maxdepth,
        tocfile=_name(args.tocfile, "--tocfile"),
        suffix=_name(args.suffix.removeprefix("."), "--suffix"),
        templatedir=args.templatedir,
        remove_old=args.remove_old,
    )
    return settings, options


class _WarningHandler(logging.Handler):
    """Print warnings like Sphinx (``location: WARNING: message [type.subtype]``)
    and count them.
    """

    def __init__(self, stream):
        super().__init__(logging.WARNING)
        self.stream = stream
        self.count = 0

    def emit(self, record):
        self.count += 1
        location = getattr(record, "location", None)
        prefix = f"{location}: " if location else ""
        label = "WARNING" if record.levelno == logging.WARNING else "ERROR"
        kind = ".".join(
            str(part)
            for part in (
                getattr(record, "type", None),
                getattr(record, "subtype", None),
            )
            if part
        )
        tail = f" [{kind}]" if kind else ""
        print(f"{prefix}{label}: {record.getMessage()}{tail}", file=self.stream)


@contextlib.contextmanager
def _sphinx_warnings(stream):
    """Route the ``sphinx`` loggers (``sphinx.util.logging``) to one handler
    while the generator runs; in-process callers keep their own handlers.
    """
    logger = logging.getLogger("sphinx")
    saved = logger.handlers[:], logger.propagate, logger.level
    handler = _WarningHandler(stream)
    logger.handlers = [handler]
    logger.propagate = False
    logger.setLevel(logging.WARNING)
    try:
        yield handler
    finally:
        logger.handlers, logger.propagate = saved[0], saved[1]
        logger.setLevel(saved[2])


def main(argv=None):
    """Run ``sphinx-matlab-apidoc``; return the exit status.

    0 on success, also with warnings; 2 for usage or settings errors
    (argparse exits with 2 itself for usage errors).
    """
    parser = get_parser()
    args = parser.parse_args(argv)
    try:
        settings, options = _settings(args)
    except ConfigError as err:
        print(f"{parser.prog}: error: {err}", file=sys.stderr)
        return USAGE_ERROR

    start = time.perf_counter()
    with _sphinx_warnings(sys.stderr) as warnings:
        source_index = build_index(settings)
        result = generate(source_index, options)
    elapsed = time.perf_counter() - start

    if not args.quiet:
        verbs = ("Would create", "Would update", "Would remove")
        if not args.dry_run:
            verbs = ("Creating", "Updating", "Removing")
        for verb, paths in zip(
            verbs, (result.created, result.updated, result.removed), strict=True
        ):
            for path in paths:
                shown = os.path.join(options.output_dir, *path.split("/"))
                print(f"{verb} file {shown}.")
        kept = f", {len(result.kept)} kept (-f overwrites)" if result.kept else ""
        print(
            f"{'Dry run: ' if args.dry_run else ''}{len(result.pages)} pages: "
            f"{len(result.created)} created, {len(result.updated)} updated, "
            f"{len(result.unchanged)} unchanged{kept}, {len(result.removed)} "
            f"removed; {len(source_index.index)} files indexed, "
            f"{warnings.count} warnings, {elapsed:.2f} s."
        )
    return 0
